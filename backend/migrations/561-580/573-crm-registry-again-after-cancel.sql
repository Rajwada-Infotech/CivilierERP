-- Migration 573: a cancelled registry can be followed by a new one.
--
-- CrmRegistry.BookingId was UNIQUE (one registry per booking, cancelled ones
-- included), so once a registry was cancelled — by staff, or with its sale
-- deed (cancelling a sale deed cancels its open registry, 2026-10-14) — a
-- corrected sale deed for the same booking could never be registered.
-- Business decision 2026-10-14: the corrected deed goes to registration
-- again. Now: at most one registry per booking that is NOT Cancelled
-- (filtered unique index); cancelled ones stay as history.
-- The old constraint's name was generated by SQL Server (differs per
-- database), so it is looked up. Safe to run again.
DECLARE @uq SYSNAME, @sql NVARCHAR(400);
SELECT TOP 1 @uq = kc.name
  FROM sys.key_constraints kc
  JOIN sys.index_columns ic ON ic.object_id = kc.parent_object_id AND ic.index_id = kc.unique_index_id
  JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
 WHERE kc.parent_object_id = OBJECT_ID(N'dbo.CrmRegistry') AND kc.type = 'UQ' AND c.name = N'BookingId'
   AND (SELECT COUNT(*) FROM sys.index_columns x WHERE x.object_id = kc.parent_object_id AND x.index_id = kc.unique_index_id) = 1;
IF @uq IS NOT NULL
BEGIN
  SET @sql = N'ALTER TABLE dbo.CrmRegistry DROP CONSTRAINT ' + QUOTENAME(@uq);
  EXEC sp_executesql @sql;
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.CrmRegistry') AND name = N'UX_CrmRegistry_Booking_Live')
  CREATE UNIQUE INDEX UX_CrmRegistry_Booking_Live ON dbo.CrmRegistry (BookingId) WHERE Status <> N'Cancelled';
GO
