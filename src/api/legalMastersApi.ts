import { fetchWithAuth } from "@/lib/fetchWithAuth";

// Legal module Setup masters — one generic endpoint per master (backend/routes/legal/legalMasters.js).
const BASE = "/api/legal/masters";

export type LegalFieldType = "text" | "textarea" | "url" | "int" | "decimal" | "date" | "bit" | "select" | "ref" | "file";

export interface LegalFieldMeta {
  name: string;
  label: string;
  type: LegalFieldType;
  required: boolean;
  options?: string[];
  /** For a "ref": the Legal master key, or "project" / "role" / "user". */
  ref?: string;
  /** For a "ref": only offer rows whose own `filterBy` column matches this form's value. */
  filterBy?: string;
  /** With filterBy: rows whose parent is blank also qualify ("any deed type"). */
  blankOk?: boolean;
  /** For a "ref": copy these columns of the picked row into empty form fields ({ FormField: "Column" }). */
  fill?: Record<string, string>;
  default?: string | number | boolean;
  upper: boolean;
  max?: number;
  /** "aadhaar": lists show XXXX XXXX 1234; sending that back unchanged keeps the stored number. */
  mask?: "aadhaar";
  /** Generated by the server on add (Land ID, enquiry number) and never edited. */
  auto?: boolean;
  /** A text field offering names from this list (pick one or type freely): "owner", "seller", "buyer", "company". */
  suggest?: string;
  /** With suggest: the party role a typed name is matched to, or added to, on save. */
  party?: string;
  /** Kept by the server (e.g. the matched party's id): not in the form or the table. */
  hidden?: boolean;
  /** Several values can be picked when adding (one row each). */
  multi?: boolean;
  /** workflow status (verification / L1 / L2): shown in lists, never in the entry form */
  system?: boolean;
  /** A "ref" whose list takes a plain name: a new name can be typed and is added to that list on save. */
  creatable?: boolean;
}

export interface LegalMasterMeta {
  key: string;
  title: string;
  group: string;
  pageKey: string;
  desc: string;
  pk: string;
  /** Rows belong to a parent record (a land property's RS records): list them with ?parent=ID. */
  parent?: string;
  /** Never physically deleted — marked inactive instead. */
  noDelete?: boolean;
  superAdminDelete?: boolean;
  /** Approval setup: only an administrator can change it; everyone else sees it read-only. */
  adminOnly?: boolean;
  /** Read-only computed columns shown in the table and details (e.g. "Used by land"). */
  /** `whatsapp`: the row also carries `<name>__wa`, a WhatsApp number shown as a chat link beside the value */
  extras?: { name: string; label: string; whatsapp?: boolean; after?: string }[];
  fields: LegalFieldMeta[];
}

