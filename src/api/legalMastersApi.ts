export const addLegalRow = async (master: string, payload: LegalRow) =>
  handle<{ id: number; message: string }>(await fetchWithAuth(`${BASE}/${master}`, json("POST", payload)));
export const updateLegalRow = async (master: string, id: number, payload: LegalRow) =>
  handle<{ message: string }>(await fetchWithAuth(`${BASE}/${master}/${id}`, json("PUT", payload)));
export const deleteLegalRow = async (master: string, id: number) =>
  handle<{ message: string }>(await fetchWithAuth(`${BASE}/${master}/${id}`, { method: "DELETE" }));

/** Upload one document for a master's file field; save the returned id on the record. */
export const uploadLegalFile = async (file: File) => {
  const body = new FormData();
  body.append("file", file);
  return handle<{ id: number; fileName: string }>(await fetchWithAuth(`${BASE}/files`, { method: "POST", body }));
};

/** Fetch an uploaded document (with the session) as a local object URL, for the in-page preview. Revoke it when done. */
export const fetchLegalFile = async (id: number | string) => {
  const res = await fetchWithAuth(`${BASE}/files/${id}`);
  if (!res.ok) throw new Error((await res.json().catch(() => ({})))?.error || "Could not load the document");
  const blob = await res.blob();
  return { url: URL.createObjectURL(blob), type: blob.type };
};

/** Open an uploaded document in a new tab (fetched with the session, so it works behind auth). */
export const openLegalFile = async (id: number | string) => {
  const tab = window.open("", "_blank");
  const res = await fetchWithAuth(`${BASE}/files/${id}`);
  if (!res.ok) {
    tab?.close();
    throw new Error((await res.json().catch(() => ({})))?.error || "Could not open the document");
  }
  const url = URL.createObjectURL(await res.blob());
  if (tab) tab.location.href = url;
  else window.location.assign(url);
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
};

