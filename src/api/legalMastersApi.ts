import { fetchWithAuth } from "@/lib/fetchWithAuth";

// Legal module Setup masters — one generic endpoint per master (backend/routes/legal/legalMasters.js).
const BASE = "/api/legal/masters";

export type LegalFieldType = "text" | "textarea" | "url" | "int" | "decimal" | "date" | "bit" | "select" | "ref" | "file";

export interface LegalFieldMeta {
  name: string;
  label: string;
  type: LegalFieldType;
  required: boolean;
  options?: string[];
  /** For a "ref": the Legal master key, or "project" / "role" / "user". */
  ref?: string;
  /** For a "ref": only offer rows whose own `filterBy` column matches this form's value. */
  filterBy?: string;
  /** With filterBy: rows whose parent is blank also qualify ("any deed type"). */
  blankOk?: boolean;
  /** For a "ref": copy these columns of the picked row into empty form fields ({ FormField: "Column" }). */
  fill?: Record<string, string>;
  default?: string | number | boolean;
  upper: boolean;
  max?: number;
  /** "aadhaar": lists show XXXX XXXX 1234; sending that back unchanged keeps the stored number. */
  mask?: "aadhaar";
  /** Generated by the server on add (Land ID, enquiry number) and never edited. */
  auto?: boolean;
}

export interface LegalMasterMeta {
  key: string;
  title: string;
  group: string;
  pageKey: string;
  desc: string;
  pk: string;
  /** Rows belong to a parent record (a land property's RS records): list them with ?parent=ID. */
  parent?: string;
  /** Never physically deleted — marked inactive instead. */
  noDelete?: boolean;
  fields: LegalFieldMeta[];
}

export type LegalRow = Record<string, unknown>;
export interface LegalOption { value: number; label: string; active?: boolean; [parent: string]: unknown }

export interface LegalSummary {
  masters: Record<string, { total: number; active: number }>;
  staleLinkDays: number;
  staleLinks: { LinkId: number; LinkLabel: string; ServiceType: string; Url: string; LastTestedDate: string | null; OfficeName: string | null }[];
  templates: { TemplateId: number; TemplateName: string; VersionNo: number; Items: number; RequiredItems: number }[];
  mouzas: { MouzaId: number; MouzaName: string; JLNo: string; District: string; RsPlots: number; RsKhatians: number; LrRors: number; PlotsWithoutRor: number }[];
}

async function handle<T = unknown>(res: Response): Promise<T> {
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(data?.error || `HTTP ${res.status}`);
  return data as T;
}

const json = (method: string, body: unknown): RequestInit => ({
  method,
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify(body),
});

