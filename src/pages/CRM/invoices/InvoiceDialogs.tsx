// An invoice's PDF, and voiding one.
import React, { useEffect, useState } from "react";
import { toast } from "sonner";
import { AlertTriangle, Ban, Download, FileText } from "lucide-react";
import { fetchWithAuth } from "@/lib/fetchWithAuth";
import { cn } from "@/lib/utils";
import { GRID_BTN, GRID_BTN_BRAND, GRID_SHEET_KEYS, GridDialog } from "@/components/crm/CrmDataTable";
import { TONE_AMBER_TEXT } from "../payments/parts";
import { BKG_API, CreditedNote, InvoiceMark, fmtDate, fmtMoney, typeLabel, type InvoiceRow } from "./config";

const { KEY_RED, LBL, TEXTAREA } = GRID_SHEET_KEYS;

export function InvoicePreviewDialog({
  invoice,
  canVoid,
  onVoid,
  onClose,
}: {
  invoice: InvoiceRow;
  canVoid?: boolean;
  onVoid?: (inv: InvoiceRow) => void;
  onClose: () => void;
}) {
  const [blobUrl, setBlobUrl] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);

  useEffect(() => {
    let objectUrl: string | null = null;
    let cancelled = false;
    fetchWithAuth(`${BKG_API}/${invoice.BookingId}/invoices/${invoice.Id}/pdf`)
      .then((r) => (r.ok ? r.blob() : Promise.reject()))
      .then((blob) => {
        if (cancelled) return;
        objectUrl = URL.createObjectURL(blob);
        setBlobUrl(objectUrl);
      })
      .catch(() => {
        if (!cancelled) setFailed(true);
      });
    return () => {
      cancelled = true;
      if (objectUrl) URL.revokeObjectURL(objectUrl);
    };
  }, [invoice.BookingId, invoice.Id]);

  const isVoid = invoice.Status === "Void";
  const lines: [string, React.ReactNode][] = [
    ["Customer", invoice.ApplicantName],
    ["Booking", `${invoice.BookingNo} · ${invoice.UnitNo}`],
    ["Project", invoice.ProjectName || "—"],
    ["Invoice date", fmtDate(invoice.InvoiceDate)],
    ["Type", typeLabel(invoice.InvoiceType)],
    ["Taxable value", fmtMoney(invoice.TaxableValue)],
    ["GST", fmtMoney(invoice.GstAmount)],
    ["Generated by", invoice.CreatedByName || "—"],
  ];

  return (
    <GridDialog
      open
      onClose={onClose}
      icon={FileText}
      width="max-w-5xl w-[96vw]"
      title={
        <span className="inline-flex items-center gap-2 flex-wrap">
          <span className="tabular-nums">{invoice.InvoiceNo}</span>
          <InvoiceMark inv={invoice} />
        </span>
      }
      description={
        <span className="tabular-nums">
          {typeLabel(invoice.InvoiceType)} · {invoice.BookingNo}
          {invoice.UnitNo ? ` · ${invoice.UnitNo}` : ""}
        </span>
      }
    >
      <div className="grid grid-cols-1 md:grid-cols-[minmax(0,1fr)_18rem] gap-5">
        <div className="flex items-center justify-center min-h-[340px] rounded-xl border border-border bg-muted/20 overflow-hidden">
          {failed ? (
            <span className="text-sm text-destructive px-4 text-center">Could not load the invoice PDF.</span>
          ) : !blobUrl ? (
            <span className="text-sm text-muted-foreground">Loading the PDF…</span>
          ) : (
            <iframe src={blobUrl} title={invoice.InvoiceNo} className="w-full h-[66vh] border-0" />
          )}
        </div>

        <aside className="rounded-xl border border-border bg-muted/20 p-4 flex flex-col gap-3.5 min-w-0">
          <div className="rounded-lg border border-border bg-card px-3.5 py-2.5 flex items-baseline justify-between gap-2">
            <span className="text-xs text-muted-foreground">Invoice total</span>
            <span className={cn("text-lg font-bold tabular-nums", isVoid && "line-through text-muted-foreground")}>
              {fmtMoney(invoice.Amount)}
            </span>
          </div>

          <dl className="text-[0.8125rem] space-y-2 flex-1">
            {lines.map(([l, v]) => (
              <div key={l} className="flex justify-between gap-3">
                <dt className="text-muted-foreground shrink-0">{l}</dt>
                <dd className="text-right tabular-nums min-w-0 break-words font-medium text-foreground">{v}</dd>
              </div>
            ))}
          </dl>

          {Number(invoice.CreditedAmount) > 0 && (
            <div className="rounded-lg border border-border bg-card px-3 py-2 text-xs">
              <CreditedNote inv={invoice} />
            </div>
          )}

          {isVoid && (
            <div className="rounded-lg border border-destructive/30 bg-destructive/10 px-3 py-2 text-xs text-destructive">
              Voided{invoice.VoidReason ? `: ${invoice.VoidReason}` : ""}
            </div>
          )}

          <div className="flex flex-col gap-2 pt-1 border-t border-border">
            {blobUrl && (
              <a href={blobUrl} download={`${invoice.InvoiceNo}.pdf`} className={cn(GRID_BTN_BRAND, "w-full justify-center")}>
                <Download size={13} /> Download PDF
              </a>
            )}
            {!isVoid && canVoid && onVoid && (
              <button type="button" onClick={() => onVoid(invoice)} className={cn(KEY_RED, "h-9 px-3 w-full justify-center")}>
                <Ban size={13} /> Void invoice
              </button>
            )}
          </div>
        </aside>
      </div>
    </GridDialog>
  );
}

export function VoidInvoiceDialog({
  invoice,
  onClose,
  onVoided,
}: {
  invoice: InvoiceRow;
  onClose: () => void;
  onVoided: () => void;
}) {
  const [reason, setReason] = useState("");
  const [busy, setBusy] = useState(false);

  async function handleVoid() {
    const trimmed = reason.trim();
    if (!trimmed) {
      toast.error("A reason is required to void an invoice");
      return;
    }
    setBusy(true);
    try {
      const res = await fetchWithAuth(`${BKG_API}/${invoice.BookingId}/invoices/${invoice.Id}/void`, {
        method: "PUT",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ reason: trimmed }),
      });
      if (!res.ok) {
        const err = await res.json().catch(() => ({ error: "Void failed" }));
        toast.error(err.error || "Void failed");
        return;
      }
      toast.success(`${invoice.InvoiceNo} voided`);
      onVoided();
    } catch {
      toast.error("Network error — could not void invoice");
    } finally {
      setBusy(false);
    }
  }

  return (
    <GridDialog
      open
      onClose={() => {
        if (!busy) onClose();
      }}
      icon={Ban}
      width="max-w-md"
      title={
        <span>
          Void <span className="tabular-nums">{invoice.InvoiceNo}</span>?
        </span>
      }
      description={
        <span className="tabular-nums">
          {typeLabel(invoice.InvoiceType)} · {fmtMoney(invoice.Amount)} · {invoice.BookingNo}
        </span>
      }
      footer={
        <>
          <button type="button" onClick={onClose} disabled={busy} className={GRID_BTN}>
            Cancel
          </button>
          <button type="button" onClick={handleVoid} disabled={busy || !reason.trim()} className={cn(KEY_RED, "h-9 px-4")}>
            <Ban size={13} /> {busy ? "Voiding…" : "Void invoice"}
          </button>
        </>
      }
    >
      <div className="flex items-start gap-2.5 rounded-lg border border-amber-500/30 bg-amber-500/10 px-3.5 py-2.5 text-xs">
        <AlertTriangle size={14} className={cn("shrink-0 mt-0.5", TONE_AMBER_TEXT)} />
        <p className="text-foreground leading-relaxed">
          Voided invoices stay in the audit trail. Once voided, you can issue a replacement invoice.
        </p>
      </div>
      <div>
        <label className={`block mb-1.5 ${LBL}`}>Reason for voiding *</label>
        <textarea
          value={reason}
          onChange={(e) => setReason(e.target.value)}
          placeholder="Why is this invoice being voided?"
          rows={3}
          className={TEXTAREA}
          autoFocus
        />
      </div>
    </GridDialog>
  );
}
