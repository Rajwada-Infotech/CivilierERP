// An invoice's PDF, and voiding one.
import React, { useEffect, useState } from "react";
import { toast } from "sonner";
import { Ban, Download, FileText } from "lucide-react";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { fetchWithAuth } from "@/lib/fetchWithAuth";
import { GRID_SHEET_KEYS } from "@/components/crm/CrmDataTable";
import { BKG_API, CreditedNote, DIALOG, InvoiceMark, fmtDate, fmtMoney, typeLabel, type InvoiceRow } from "./config";

const { KEY_INK, KEY_LINE, KEY_RED, LBL, RULE, RULE_SOFT, TEXTAREA } = GRID_SHEET_KEYS;

export function InvoicePreviewDialog({ invoice, canVoid, onVoid, onClose }: { invoice: InvoiceRow; canVoid?: boolean; onVoid?: (inv: InvoiceRow) => void; onClose: () => void }) {
  const [blobUrl, setBlobUrl] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    let objectUrl: string | null = null;
    let cancelled = false;
    fetchWithAuth(`${BKG_API}/${invoice.BookingId}/invoices/${invoice.Id}/pdf`)
      .then((r) => (r.ok ? r.blob() : Promise.reject()))
      .then((blob) => {
        if (cancelled) return;
        objectUrl = URL.createObjectURL(blob);
        setBlobUrl(objectUrl);
      })
      .catch(() => { if (!cancelled) setFailed(true); });
    return () => { cancelled = true; if (objectUrl) URL.revokeObjectURL(objectUrl); };
  }, [invoice.BookingId, invoice.Id]);
  const isVoid = invoice.Status === "Void";
  const lines: [string, React.ReactNode][] = [
    ["Customer", invoice.ApplicantName],
    ["Booking", `${invoice.BookingNo} · ${invoice.UnitNo}`],
    ["Project", invoice.ProjectName || "—"],
    ["Invoice date", fmtDate(invoice.InvoiceDate)],
    ["Type", typeLabel(invoice.InvoiceType)],
    ["Taxable value", fmtMoney(invoice.TaxableValue)],
    ["GST", fmtMoney(invoice.GstAmount)],
    ["Invoice amount", <b key="a">{fmtMoney(invoice.Amount)}</b>],
    ["Generated by", invoice.CreatedByName || "—"],
  ];
  return (
    <Dialog open onOpenChange={(o) => !o && onClose()}>
      <DialogContent className={`max-w-5xl w-[96vw] ${DIALOG}`} style={{ border: RULE }}>
        <DialogHeader>
          <div className="flex items-center gap-2 flex-wrap pr-6">
            <DialogTitle className="flex items-center gap-2 tabular-nums"><FileText size={15} /> {invoice.InvoiceNo}</DialogTitle>
            <InvoiceMark inv={invoice} />
          </div>
          <DialogDescription className="sr-only">{typeLabel(invoice.InvoiceType)} invoice for {fmtMoney(invoice.Amount)}</DialogDescription>
        </DialogHeader>
        <div className="grid grid-cols-1 md:grid-cols-[minmax(0,1fr)_17rem] gap-4">
          <div className="flex items-center justify-center min-h-[300px] rounded-md overflow-hidden" style={{ border: RULE_SOFT }}>
            {failed ? <span className="text-sm text-destructive">Could not load the invoice PDF.</span>
              : !blobUrl ? <span className="text-sm text-muted-foreground">Loading the PDF…</span>
              : <iframe src={blobUrl} title={invoice.InvoiceNo} className="w-full h-[68vh] border-0" />}
          </div>
          <div className="space-y-3 min-w-0">
            <dl className="text-[0.8125rem] space-y-2">
              {lines.map(([l, v]) => <div key={l} className="flex justify-between gap-3"><dt className="text-muted-foreground shrink-0">{l}</dt><dd className="text-right tabular-nums min-w-0 break-words">{v}</dd></div>)}
            </dl>
            <CreditedNote inv={invoice} />
            {isVoid && <p className="text-xs text-destructive">Voided{invoice.VoidReason ? `: ${invoice.VoidReason}` : ""}</p>}
            <div className="flex flex-col gap-2 pt-1">
              {blobUrl && <a href={blobUrl} download={`${invoice.InvoiceNo}.pdf`} className={`${KEY_INK} h-9 px-3`}><Download size={13} /> Download PDF</a>}
              {!isVoid && canVoid && onVoid && <button type="button" onClick={() => onVoid(invoice)} className={`${KEY_LINE} h-9 px-3 !text-destructive`}><Ban size={13} /> Void invoice</button>}
            </div>
          </div>
        </div>
      </DialogContent>
    </Dialog>
  );
}

export function VoidInvoiceDialog({ invoice, onClose, onVoided }: { invoice: InvoiceRow; onClose: () => void; onVoided: () => void }) {
  const [reason, setReason] = useState("");
  const [busy, setBusy] = useState(false);

  async function handleVoid() {
    const trimmed = reason.trim();
    if (!trimmed) { toast.error("A reason is required to void an invoice"); return; }
    setBusy(true);
    try {
      const res = await fetchWithAuth(`${BKG_API}/${invoice.BookingId}/invoices/${invoice.Id}/void`, {
        method: "PUT", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ reason: trimmed }),
      });
      if (!res.ok) {
        const err = await res.json().catch(() => ({ error: "Void failed" }));
        toast.error(err.error || "Void failed");
        return;
      }
      toast.success(`${invoice.InvoiceNo} voided`);
      onVoided();
    } catch {
      toast.error("Network error — could not void invoice");
    } finally {
      setBusy(false);
    }
  }

  return (
    <Dialog open onOpenChange={(o) => !o && onClose()}>
      <DialogContent className={`max-w-md ${DIALOG}`} style={{ border: RULE }}>
        <DialogHeader>
          <DialogTitle className="font-heading flex items-center gap-2"><Ban size={15} /> Void {invoice.InvoiceNo}?</DialogTitle>
          <DialogDescription className="text-xs tabular-nums">
            {typeLabel(invoice.InvoiceType)} · {fmtMoney(invoice.Amount)} · {invoice.BookingNo}. It stays on record, and a corrected invoice can then be generated in its place.
          </DialogDescription>
        </DialogHeader>
        <div>
          <label className={`block mb-1 ${LBL}`}>Reason *</label>
          <textarea value={reason} onChange={(e) => setReason(e.target.value)} placeholder="Why is this invoice being voided?" rows={3} className={TEXTAREA} autoFocus />
        </div>
        <DialogFooter className="gap-2">
          <button onClick={onClose} disabled={busy} className={`${KEY_LINE} h-9 px-4`}>Cancel</button>
          <button onClick={handleVoid} disabled={busy || !reason.trim()} className={`${KEY_RED} h-9 px-4`}><Ban size={13} /> {busy ? "Voiding…" : "Void invoice"}</button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
